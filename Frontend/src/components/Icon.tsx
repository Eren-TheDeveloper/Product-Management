export type IconName = keyof typeof paths;

export function Icon({
  name,
  size = 20,
  className = "",
  style,
}: {
  name: IconName;
  size?: number;
  className?: string;
  style?: CSSProperties;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.65"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={style}
      aria-hidden="true"
    >
      {paths[name]}
    </svg>
  );
}

export function ProductArt({
  name,
  id,
  large = false,
}: {
  name: string;
  id: number;
  large?: boolean;
}) {
  const text = name.toLocaleLowerCase("tr-TR");
  const icon: IconName = text.includes("kulaklık")
    ? "headphones"
    : text.includes("klavye")
      ? "keyboard"
      : text.includes("lamba")
        ? "lamp"
        : text.includes("monitör") || text.includes("laptop")
          ? "monitor"
          : text.includes("mouse")
            ? "mouse"
            : text.includes("hoparlör")
              ? "speaker"
              : text.includes("kamera")
                ? "camera"
                : text.includes("kablo") ||
                    text.includes("şarj") ||
                    text.includes("usb")
                  ? "plug"
                  : "box";
  return (
    <span className={`product-art art-${id % 6} ${large ? "large" : ""}`}>
      <Icon name={icon} size={large ? 52 : 23} />
    </span>
  );
}
